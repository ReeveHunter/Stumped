#!/usr/bin/env python3
"""Builds src/fewest.h from data/fewest.txt (fewest moves) and data/fewest-pushes.txt (fewest pushes).

Every solution is replayed against its level before it goes in; a line that doesn't solve its level
with exactly the counts it claims stops the build. Levels with no proven count get 0 (the game then
shows nothing for that number)."""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRS = {'l': (-1, 0), 'r': (1, 0), 'u': (0, -1), 'd': (0, 1)}


def is_map_line(s):
    return s and all(c in ' #@$.*+-_' for c in s) and '#' in s


def load_sets():
    sets = {}
    folder = os.path.join(ROOT, 'levels')
    for fn in sorted(os.listdir(folder)):
        if not fn.endswith('.txt') or fn == 'CREDITS.txt':
            continue
        name = fn.split('-', 1)[1][:-4] if '-' in fn else fn[:-4]
        maps, cur, first = [], [], True
        for line in open(os.path.join(folder, fn), encoding='utf-8', errors='replace'):
            line = line.rstrip('\r\n').rstrip(' ')
            if first and line.startswith(';'):
                t = line[1:].strip()
                if t and not t[0].isdigit():
                    name = t
                first = False
                continue
            if is_map_line(line):
                cur.append(line.replace('-', ' ').replace('_', ' '))
            elif cur:
                maps.append(cur)
                cur = []
        if cur:
            maps.append(cur)
        sets[name] = maps
    return sets


def replay(rows, sol):
    walls, boxes, goals, pl = set(), set(), set(), None
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == '#': walls.add((x, y))
            if c in '.*+': goals.add((x, y))
            if c in '$*': boxes.add((x, y))
            if c in '@+': pl = (x, y)
    moves = pushes = 0
    for ch in sol:
        dx, dy = DIRS[ch.lower()]
        n = (pl[0] + dx, pl[1] + dy)
        if n in walls:
            return None
        if n in boxes:
            b = (n[0] + dx, n[1] + dy)
            if not ch.isupper() or b in walls or b in boxes:
                return None
            boxes.remove(n); boxes.add(b); pushes += 1
        elif ch.isupper():
            return None
        pl = n; moves += 1
    return (moves, pushes) if boxes <= goals else None


def read(fn, sets, col):
    out = {}
    path = os.path.join(ROOT, 'data', fn)
    if not os.path.exists(path):
        return out
    for line in open(path):
        if line.startswith('#') or not line.strip():
            continue
        name, lv, m, p, sol = line.rstrip('\n').split('|')
        lv, m, p = int(lv), int(m), int(p)
        if name not in sets or not 1 <= lv <= len(sets[name]):
            sys.exit(f'{fn}: unknown level {name} {lv}')
        if replay(sets[name][lv - 1], sol) != (m, p):
            sys.exit(f'{fn}: the solution for {name} {lv} does not check out')
        out[(name, lv)] = (m, p)[col]
    return out


def main():
    sets = load_sets()
    fm = read('fewest.txt', sets, 0)
    fp = read('fewest-pushes.txt', sets, 1)
    names = [n for n in sets if any((n, i) in fm or (n, i) in fp for i in range(1, len(sets[n]) + 1))]
    lines = ['/* Generated by tools/make_fewest.py from data/fewest.txt and data/fewest-pushes.txt: the proven',
             '   fewest moves and fewest pushes for each level (0 = not proven). Don\'t edit by hand. */',
             'typedef struct { const char *set; int n; const unsigned short *moves, *pushes; } Fewest;']
    for k, n in enumerate(names):
        cnt = len(sets[n])
        for tag, d in (('M', fm), ('P', fp)):
            vals = [str(d.get((n, i), 0)) for i in range(1, cnt + 1)]
            body = ',\n    '.join(','.join(vals[i:i + 20]) for i in range(0, cnt, 20))
            lines.append(f'static const unsigned short FEWEST_{tag}{k}[{cnt}] = {{\n    {body} }};')
    lines.append('static const Fewest FEWEST[] = {')
    for k, n in enumerate(names):
        lines.append(f'    {{ "{n}", {len(sets[n])}, FEWEST_M{k}, FEWEST_P{k} }},')
    lines.append('    { 0, 0, 0, 0 }\n};')
    open(os.path.join(ROOT, 'src', 'fewest.h'), 'w').write('\n'.join(lines) + '\n')
    for n in names:
        c = len(sets[n])
        print(f'{n}: fewest moves for {sum((n, i) in fm for i in range(1, c + 1))}/{c}, '
              f'fewest pushes for {sum((n, i) in fp for i in range(1, c + 1))}/{c}')


main()
