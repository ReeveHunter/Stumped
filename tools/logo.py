"""Stumped title logo: the game font's letters with a leafy vine weaving over and under them.
Writes src/logo.h (base image + leaves with two rustle frames) and a preview."""
import re, math, sys
from PIL import Image
import os
ROOT=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src=open(ROOT+'/deps/font8x8_basic.h').read()
rows=re.findall(r'\{\s*(0x[0-9A-Fa-f]{2}(?:\s*,\s*0x[0-9A-Fa-f]{2}){7})\s*\}',src)
F={chr(i):[int(v,16) for v in rows[i].split(',')] for i in range(128)}
NIGHT=[(0x9A,0xA8,0xD8),(0x5C,0x6C,0xA8),(0x2E,0x38,0x68),(0x0C,0x10,0x28)]
W,H=132,32; X0,Y0=10,9          # art pixels (shown at 3x, like the title sprites)
def inb(x,y): return 0<=x<W and 0<=y<H
def glyph_mask():
    m=[[0]*W for _ in range(H)]
    for k,ch in enumerate("STUMPED"):
        for r in range(8):
            for b in range(8):
                if F[ch][r]>>b&1:
                    for dy in range(2):
                        for dx in range(2): m[Y0+2*r+dy][X0+16*k+2*b+dx]=1
    return m
def vine_y(x): return Y0 + 6.5 + 4.5*math.sin((x - X0 - 2) / 5.3)
# leaves pointing up-right (flipped for the other directions); frame 1 = caught by the breeze
LEAF_UP=[["....333", "..30003", ".301113", "3011123", "311123.", "3223...", "3......"],
         ["...33..", "..3003.", "..30113", ".301113", ".31123.", ".3223..", "3......"]]
def leaf_cells(frame, down, flip):
    art=LEAF_UP[frame]; out={}
    for y,row in enumerate(art):
        for x,c in enumerate(row):
            if c!='.':
                dx=-x if flip else x
                dy=(y-6) if not down else (6-y)
                out[(dx,dy)]=int(c)
    return out
def build():
    m=glyph_mask(); g=[[None]*W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            if m[y][x]: g[y][x]=3
            elif y>0 and x>0 and m[y-1][x-1]: g[y][x]=2
    vine=set(); prev=None
    x_from,x_to=X0-4, X0+16*7+3
    for x in range(x_from,x_to+1):
        yi=int(math.floor(vine_y(x)))
        lo,hi=(yi,yi) if prev is None else (min(prev,yi),max(prev,yi))
        for yy in range(lo,hi+2): vine.add((x,yy))
        prev=yi
    over=lambda x: ((x-X0)//16)%2==0           # over every other letter, under the rest
    for (x,y) in vine:
        if not inb(x,y): continue
        edge=(x,y+1) not in vine or (x,y-1) not in vine
        if m[y][x]:
            if over(x): g[y][x]= 1 if edge else 2
        else: g[y][x]= 3 if edge else 2
    # a tendril curling at each end
    for cx,cy,s in ((x_from,int(vine_y(x_from)),-1),(x_to,int(vine_y(x_to)),1)):
        for i in range(0,400,3):
            a=math.radians(i); r=3.6*(1-i/480)
            x=int(round(cx+s*(3.6-r*math.cos(a)))) ; y=int(round(cy-r*math.sin(a)))
            if inb(x,y) and not m[y][x]: g[y][x]=3
    leaves=[]
    for i,x in enumerate(range(X0+1, X0+16*7, 10)):
        y=int(math.floor(vine_y(x)))
        down=i%2==1
        leaves.append((x, y+2 if down else y-1, down, False))
    return g,leaves
def render(g,leaves,frames):
    out=[r[:] for r in g]
    for (x,y,down,flip),f in zip(leaves,frames):
        for (dx,dy),v in leaf_cells(f,down,flip).items():
            if inb(x+dx,y+dy): out[y+dy][x+dx]=v
    return out
def write_header(g,leaves,path):
    L=[]
    L.append('/* generated by tools/logo.py: the title logo (shades 0..3, 255 = clear) */')
    L.append('#define LOGO_W %d\n#define LOGO_H %d\n#define NUM_LOGO_LEAVES %d' % (W,H,len(leaves)))
    L.append('static const uint8_t LOGO[LOGO_H][LOGO_W] = {')
    for row in g: L.append('    {' + ','.join(str(255 if v is None else v) for v in row) + '},')
    L.append('};')
    L.append('/* leaf sprites: [frame][down][7][7], anchored at row 6 col 0 (or row 0 when hanging down) */')
    L.append('static const uint8_t LOGO_LEAF[2][2][7][7] = {')
    for f in range(2):
        L.append('  {')
        for down in range(2):
            grid=[[255]*7 for _ in range(7)]
            for (dx,dy),v in leaf_cells(f,down,False).items(): grid[dy+ (6 if not down else 0)][dx]=v
            L.append('    {' + ','.join('{'+','.join(map(str,r))+'}' for r in grid) + '},')
        L.append('  },')
    L.append('};')
    L.append('static const struct { int8_t x, y, down; } LOGO_LEAVES[NUM_LOGO_LEAVES] = {')
    L.append('    ' + ', '.join('{%d,%d,%d}' % (x, y - (6 if not d else 0), int(d)) for x,y,d,_ in leaves))
    L.append('};')
    open(path,'w').write('\n'.join(L)+'\n')
if __name__ == '__main__':
    g,leaves=build()
    write_header(g,leaves,ROOT+'/src/logo.h')
    # preview
    sc=6; im=Image.new('RGB',(W*sc,H*sc*2+sc),NIGHT[0])
    for k,frames in enumerate(([0]*len(leaves),[1]*len(leaves))):
        out=render(g,leaves,frames)
        for y in range(H):
            for x in range(W):
                v=out[y][x]
                if v is not None: im.paste(NIGHT[v],(x*sc,(y+k*(H+1))*sc,(x+1)*sc,(y+k*(H+1)+1)*sc))
    im.save(os.path.join(ROOT, 'docs', 'logo-preview.png'))
